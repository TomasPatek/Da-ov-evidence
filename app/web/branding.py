"""Company branding stored in /config/branding: logo and theme.css."""

from __future__ import annotations

import re
from pathlib import Path

from app.storage.atomic import atomic_write_bytes, atomic_write_text

DEFAULT_THEME = Path(__file__).parent / "static" / "css" / "theme-default.css"
MAX_LOGO_BYTES = 1024 * 1024
LOGO_NAMES = ("logo.svg", "logo.png")

_HEX_COLOR = re.compile(r"^#[0-9a-fA-F]{6}$")
_SVG_FORBIDDEN = re.compile(
    rb"<script|<foreignobject|javascript:|\son[a-z]+\s*=|<!entity|xlink:href\s*=\s*[\"']?https?:",
    re.IGNORECASE,
)


class BrandingError(ValueError):
    pass


def logo_path(branding_dir: Path) -> Path | None:
    for name in LOGO_NAMES:
        candidate = branding_dir / name
        if candidate.is_file():
            return candidate
    return None


def theme_path(branding_dir: Path) -> Path:
    custom = branding_dir / "theme.css"
    return custom if custom.is_file() else DEFAULT_THEME


def detect_logo_type(data: bytes) -> str:
    """Return 'png' or 'svg' based on content (never trust the filename)."""
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "png"
    head = data[:2048].lstrip(b"\xef\xbb\xbf").lstrip().lower()
    if (head.startswith(b"<?xml") or head.startswith(b"<svg") or head.startswith(b"<!--")) and (
        b"<svg" in data[:4096].lower()
    ):
        if _SVG_FORBIDDEN.search(data):
            raise BrandingError("SVG obsahuje skripty nebo externí odkazy, které nejsou povolené.")
        return "svg"
    raise BrandingError("Logo musí být ve formátu PNG nebo SVG.")


def save_logo(branding_dir: Path, data: bytes) -> Path:
    if len(data) > MAX_LOGO_BYTES:
        raise BrandingError("Logo je větší než 1 MB.")
    if not data:
        raise BrandingError("Soubor s logem je prázdný.")
    kind = detect_logo_type(data)
    target = branding_dir / f"logo.{kind}"
    atomic_write_bytes(target, data)
    for name in LOGO_NAMES:
        other = branding_dir / name
        if other != target and other.exists():
            other.unlink()
    return target


def _contrast_text(hex_color: str) -> str:
    r, g, b = (int(hex_color[i : i + 2], 16) / 255 for i in (1, 3, 5))

    def channel(c: float) -> float:
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    luminance = 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)
    return "#000000" if luminance > 0.179 else "#ffffff"


def write_theme(branding_dir: Path, primary: str, accent: str) -> None:
    for color in (primary, accent):
        if not _HEX_COLOR.match(color):
            raise BrandingError(f"Neplatná barva: {color!r}. Použijte tvar #RRGGBB.")
    css = f"""/* Generated by the setup wizard. Edit freely; see docs/konfigurace.md. */
:root {{
  --brand-primary: {primary.lower()};
  --brand-primary-contrast: {_contrast_text(primary)};
  --brand-accent: {accent.lower()};
  --brand-accent-contrast: {_contrast_text(accent)};
}}
"""
    atomic_write_text(branding_dir / "theme.css", css)


def current_colors(branding_dir: Path) -> tuple[str, str]:
    css = theme_path(branding_dir).read_text(encoding="utf-8")

    def find(var: str, default: str) -> str:
        m = re.search(rf"--{var}:\s*(#[0-9a-fA-F]{{6}})\s*;", css)
        return m.group(1) if m else default

    return find("brand-primary", "#2f5d8a"), find("brand-accent", "#d98e04")
